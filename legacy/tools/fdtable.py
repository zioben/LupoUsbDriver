#!/usr/bin/env python3
"""
LupoUsbDriver legacy port: build the library jump table from an .fd file.

StormC generated the function table of lupousb.library automatically from
LupoUsbLibrary.fd ("#pragma libbase"). With gcc the table is written
explicitly: this tool emits a C file with the user functions in .fd order
(first entry at bias 30, after Open/Close/Expunge/Reserved).

usage: fdtable.py FILE.fd OUT.c
"""
import re
import sys


def main():
    fd, out = sys.argv[1], sys.argv[2]
    names = []
    bias = None
    for line in open(fd, encoding='latin-1'):
        line = line.strip()
        if not line or line.startswith('*'):
            continue
        if line.startswith('##bias'):
            bias = int(line.split()[1])
            continue
        if line.startswith('##'):
            continue
        m = re.match(r'([A-Za-z_]\w*)\s*\(', line)
        if m:
            names.append(m.group(1))
    if bias != 30:
        sys.exit('fdtable: unexpected ##bias %s' % bias)
    with open(out, 'w') as f:
        f.write('/* Generated by legacy/tools/fdtable.py from %s - do not edit */\n' % fd)
        for n in names:
            f.write('extern void %s(void);\n' % n)
        f.write('extern void lib_open(void);\nextern void lib_close(void);\n'
                'extern void lib_expunge(void);\nextern void lib_null(void);\n')
        f.write('\n/* Open, Close, Expunge, Reserved, then the .fd functions */\n')
        f.write('const void *const lupousb_functable[] = {\n')
        f.write('    (const void *)lib_open, (const void *)lib_close,\n'
                '    (const void *)lib_expunge, (const void *)lib_null,\n')
        for i, n in enumerate(names):
            f.write('    (const void *)%s,   /* -%d */\n' % (n, 30 + 6 * i))
        f.write('    (const void *)-1\n};\n')
    print('fdtable: %d functions' % len(names))


if __name__ == '__main__':
    main()
